#!/usr/bin/env python3
"""把 Lucide 图标（ISC）转换成 Android VectorDrawable。

图标全部来自 https://lucide.dev（lucide-static，ISC 许可），版本钉死在 LUCIDE_VERSION，
避免构建时联网。生成结果提交到 app/src/main/res/drawable/。

用法：
  python tools/fetch_lucide_icons.py
"""

