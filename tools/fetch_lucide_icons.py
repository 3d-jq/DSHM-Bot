PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = PROJECT_ROOT / "app" / "src" / "main" / "res" / "drawable"
SVG_NS = "{http://www.w3.org/2000/svg}"


def _num(value: str | None, default: float = 0.0) -> float:
    if value is None:
        return default
    return float(value)


def _fmt(value: float) -> str:
    if abs(value - round(value)) < 1e-6:
        return str(int(round(value)))
    return f"{value:.3f}".rstrip("0").rstrip(".")


def _circle_path(cx: float, cy: float, rx: float, ry: float) -> str:
    return (
        f"M {_fmt(cx - rx)} {_fmt(cy)} "
        f"a {_fmt(rx)} {_fmt(ry)} 0 1 0 {_fmt(rx * 2)} 0 "
        f"a {_fmt(rx)} {_fmt(ry)} 0 1 0 {_fmt(-rx * 2)} 0"
    )


def _rect_path(x: float, y: float, width: float, height: float, rx: float, ry: float) -> str:
    if rx <= 0 and ry <= 0:
        return f"M {_fmt(x)} {_fmt(y)} h {_fmt(width)} v {_fmt(height)} h {_fmt(-width)} Z"
    rx = rx or ry
    ry = ry or rx
    return (
        f"M {_fmt(x + rx)} {_fmt(y)} "
        f"h {_fmt(width - 2 * rx)} "
        f"a {_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(rx)} {_fmt(ry)} "
        f"v {_fmt(height - 2 * ry)} "
        f"a {_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(-rx)} {_fmt(ry)} "
        f"h {_fmt(-(width - 2 * rx))} "
        f"a {_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(-rx)} {_fmt(-ry)} "
        f"v {_fmt(-(height - 2 * ry))} "
        f"a {_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(rx)} {_fmt(-ry)} Z"
    )


def _polyline_path(points: str, close: bool) -> str:
    coords = [float(part) for part in points.replace(",", " ").split()]
    pairs = list(zip(coords[0::2], coords[1::2]))
    if not pairs:
        return ""
    path = f"M {_fmt(pairs[0][0])} {_fmt(pairs[0][1])}"
    for x, y in pairs[1:]:
        path += f" L {_fmt(x)} {_fmt(y)}"
    return path + (" Z" if close else "")


def svg_to_paths(svg_text: str) -> list[str]:
    root = ET.fromstring(svg_text)
    paths: list[str] = []
    for element in root.iter():
        tag = element.tag.replace(SVG_NS, "")
        if tag == "path":
            paths.append(element.attrib.get("d", ""))
        elif tag == "circle":
            radius = _num(element.attrib.get("r"))
            paths.append(_circle_path(_num(element.attrib.get("cx")), _num(element.attrib.get("cy")), radius, radius))
        elif tag == "ellipse":
            paths.append(
                _circle_path(
                    _num(element.attrib.get("cx")),
                    _num(element.attrib.get("cy")),
                    _num(element.attrib.get("rx")),
                    _num(element.attrib.get("ry")),
                )
            )
        elif tag == "line":
            paths.append(
                f"M {_fmt(_num(element.attrib.get('x1')))} {_fmt(_num(element.attrib.get('y1')))} "
                f"L {_fmt(_num(element.attrib.get('x2')))} {_fmt(_num(element.attrib.get('y2')))}"
            )
        elif tag in ("polyline", "polygon"):
            paths.append(_polyline_path(element.attrib.get("points", ""), close=tag == "polygon"))
        elif tag == "rect":
            paths.append(
                _rect_path(
                    _num(element.attrib.get("x")),
                    _num(element.attrib.get("y")),
                    _num(element.attrib.get("width")),
                    _num(element.attrib.get("height")),
                    _num(element.attrib.get("rx")),
                    _num(element.attrib.get("ry")),
                )
            )
    return [path for path in paths if path]


def vector_xml(paths: list[str]) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/fetch_lucide_icons.py from Lucide (ISC). Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24">',
    ]
    for path in paths:
        lines.append(
            "    <path"
            f' android:pathData="{path}"'
            ' android:fillColor="@android:color/transparent"'
            ' android:strokeColor="#FF000000"'
            ' android:strokeWidth="2"'
            ' android:strokeLineCap="round"'
            ' android:strokeLineJoin="round" />'
        )
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def fetch(name: str) -> str:
    url = CDN.format(version=LUCIDE_VERSION, name=name)
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def fetch_from_dir(directory: Path):
    """离线模式：从本地目录读 <name>.svg（用 --svg-dir 指定，便于受限网络环境）。"""

    def read(name: str) -> str:
        return (directory / f"{name}.svg").read_text(encoding="utf-8")

    return read


def generate(out_dir: Path, fetch_icon=fetch) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in ICONS:
        paths = svg_to_paths(fetch_icon(name))
        if not paths:
            raise ValueError(f"Lucide icon {name} produced no paths")
        target = out_dir / f"ic_lucide_{name.replace('-', '_')}.xml"
        target.write_text(vector_xml(paths), encoding="utf-8")
        written.append(target)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description="Fetch Lucide icons as Android VectorDrawables")
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--svg-dir", type=Path, default=None, help="use local <name>.svg files instead of the CDN")
    args = parser.parse_args()
    fetch_icon = fetch_from_dir(args.svg_dir) if args.svg_dir else fetch
    for path in generate(args.out, fetch_icon=fetch_icon):
        print(path)


if __name__ == "__main__":
    main()

